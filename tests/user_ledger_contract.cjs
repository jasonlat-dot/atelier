const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require(require.resolve('typescript', { paths: [path.join(__dirname, '../apps/web')] }));
const source = fs.readFileSync(path.join(__dirname, '../apps/web/src/features/admin/userLedgerGroups.ts'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
const output = { exports: {} };
vm.runInNewContext(`(function(exports){${code}})`, {})(output.exports);
const { groupLedger } = output.exports;
const row = (id, type, balance_delta, held_delta, ref_id = 'task-a', ref_type = 'job') => ({ id, type, balance_delta, held_delta, ref_id, ref_type, created_at: `2026-10-24T00:00:${String(id).padStart(2, '0')}Z` });
const hold = row(1, 'HOLD', 0, 4);
const settled = row(2, 'SETTLE', -2, -2);
const released = row(3, 'RELEASE', 0, -2);
let groups = groupLedger([released, settled, hold]);
assert.equal(groups.length, 1);
assert.equal(groups[0].amount, -2);
assert.equal(groups[0].held, 0);
assert.equal(groups[0].state, '已结算');
assert.equal(groupLedger([hold])[0].amount, 0, 'hold is not a balance debit');
assert.equal(groupLedger([hold])[0].state, '预占中');
assert.equal(groupLedger([settled, hold])[0].state, '部分结算');
groups = groupLedger([row(4, 'RELEASE', 0, -4), hold]);
assert.equal(groups[0].amount, 0);
assert.equal(groups[0].state, '已释放');
groups = groupLedger([row(4, 'REFUND', 2, 0, 'task-a', 'job_refund'), released, settled, hold]);
assert.equal(groups.length, 1, 'compensation shares the actual task reference');
assert.equal(groups[0].amount, 0);
assert.equal(groups[0].state, '已补偿');
groups = groupLedger([released, settled, hold, settled]);
assert.equal(groups[0].entries.length, 3, 'page overlap must not count a ledger ID twice');
assert.equal(groups[0].amount, -2);
assert.equal(groupLedger([hold, row(4, 'HOLD', 0, 3, 'task-b')]).length, 2, 'different tasks stay separate');
assert.equal(groupLedger([row(1, 'HOLD', 0, 4, null, null), row(2, 'SETTLE', -2, -2, null, null)]).length, 2, 'legacy records are never guessed into a task');
groups = groupLedger([row(4, 'CHECKIN', 10, 0, null, null), row(5, 'ADMIN_ADJUST', -1, 0, null, null)]);
assert.equal(groups[0].category, 'admin');
assert.equal(groups[1].category, 'reward');
assert.equal(groups[1].amount, 10);
assert.equal(groups[1].state, '');
console.log('User ledger grouping regressions passed: task references, holds, partial settlement, release, compensation and pagination');
